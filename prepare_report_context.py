    lines += [
        "## 4. ADE / MDE Field Test Data",
        "",
        "> Hand-measured values from site visits. FRC must come from here — not from ORP.",
        "",
        "| Date | Context Point | Parameter | Value | Engineer |",
        "|---|---|---|---|---|",
    ]
    for row in ade_data:
        dt = str(row.get("CreatedDateTime", ""))[:10]
        lines.append(
            f"| {dt} | {row.get('ContextVertexName','')} "
            f"| {row.get('Parameter','')} | {row.get('Value','')} "
            f"| {row.get('PSRFullName','')} |"
        )

    # FRC highlight
    frc_rows = [r for r in ade_data if any(
        k in str(r.get("Parameter","")).lower()
        for k in ("free residual", "frc", "halogen")
    )]
