# ── Helpers ───────────────────────────────────────────────────────────────────

def _load_json(path: Path, default):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return default


def _strip_html(html: str) -> str:
    if not html:
        return ""
    text = re.sub(r"<[^>]+>", " ", html)
    for ent, rep in [("&nbsp;", " "), ("&amp;", "&"), ("&lt;", "<"), ("&gt;", ">")]:
        text = text.replace(ent, rep)
    return re.sub(r"\s{2,}", " ", text).strip()



def _create_output_stubs(root, site_name, reporting_month):
    """
    Create the empty output files and scripts folder so Copilot Agent
    can write to them directly without needing to create new files.
    """
    slug = slugify(f"{site_name}_{reporting_month}")

    # output folder + empty .md and .docx stubs
    out_dir = root / "output"
    out_dir.mkdir(exist_ok=True)

    md_file = out_dir / f"{slug}_report.md"
    if not md_file.exists():
        md_file.write_text(
            f"# {site_name}\n## {reporting_month} — Pending Copilot generation\n",
            encoding="utf-8"
        )

    docx_stub = out_dir / f"{slug}_report.docx"
    if not docx_stub.exists():
        docx_stub.write_bytes(b"")   # empty placeholder

    # scripts folder for the Node.js build script Copilot will write
    scripts_dir = root / "scripts"
    scripts_dir.mkdir(exist_ok=True)
    readme = scripts_dir / "README.md"
    if not readme.exists():
        readme.write_text(
            "# Scripts\nCopilot writes `build_report.js` here when generating the Word document.\n",
            encoding="utf-8"
        )

    print(f"✅  Output stubs created:")
    print(f"    {md_file.relative_to(root)}  ← open this in VS Code before running Copilot")
    print(f"    {docx_stub.relative_to(root)}")
    print(f"    {scripts_dir.relative_to(root)}/  ← Copilot will write build_report.js here")


if __name__ == "__main__":
    main()