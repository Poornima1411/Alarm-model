        # Group by controller
        by_ctrl: dict = {}
        for row in scc_data:
            ctrl = row.get("ControllerId", "unknown")
            by_ctrl.setdefault(ctrl, []).append(row)

        for ctrl_id, rows in by_ctrl.items():
            lines += [f"### Controller: {ctrl_id}", ""]

            # Alarm limits table (sensors that have HH/LL/H/L but no relay)
            alarm_rows = [r for r in rows if r.get("HH") or r.get("LL") or r.get("H") or r.get("L")]
